// 明确未接入的实体操作在工具循环之前拒绝；叙事事实不能充当实体 CRUD。
// 这里只拦已知能力缺口，不把出现“小镇”地点词的普通聊天/朋友圈拒绝掉。
export function capabilityBoundary(input = '') {
  const text = String(input).normalize('NFKC');
  const town = /小镇|镇上|镇里|镇内|town\b/i.test(text);
  const townEntity = /店|建筑|居民|镇民|NPC|地图|咖啡馆|酒馆|工坊|钱包|金币|房屋|道路/i.test(text);
  const manage = /改名|更名|改叫|改成|改为|命名|叫作|叫做|以后(?:就)?叫|从此(?:就)?叫|名字.*改|名称.*改|修改|更改|更换|换成|编辑|删除|移除|拆除|建造|建设|新建|增加|添加|搬迁|移动|升级|装修|调整|设置|交易|购买|出售|转账|赠送|启用|停用|关闭|打开|管理|rename|delete|update|build/i.test(text);
  if (town && townEntity && manage) return '吾神，小镇管理能力尚未接入，我不能修改小镇记录，也不能用世界事件、改人设或发布动态代替执行。请在小镇页面操作。';
  if (/(?:删除|移除|清除|删掉|delete).{0,20}(?:角色|人物卡|居民)|(?:角色|人物卡).{0,15}(?:删除|删掉)/i.test(text)) return '吾神，删除角色的能力尚未接入，我不能用修改人设、关系或世界事件替代删除。请在角色管理页面操作。';
  if (/(?:放大|超分|upscale).{0,30}(?:图片|图像|照片|相册|任务\s*\d)|(?:图片|图像|照片|相册|任务\s*\d).{0,30}(?:放大|超分|upscale)/i.test(text)) return '吾神，现有图片放大的工具尚未接入，我不能把重新生成当作放大完成。请从图片预览的放大入口操作。';
  return null;
}
