/**
 * characterNameGuard.js —— 把「角色名」从文本里洗掉
 *
 * ── 为什么需要它（规则34 的用户口径）──
 *
 * 图库（形态 `gallery`）在设定上是一个**匿名成人图片站**：上传者是匿名网名，
 * 画面里的角色只是"被画的对象"。但生成链路曾经把角色名塞给模型当"出镜名单"，
 * 模型于是把它照抄进**作品名**，产出「爻光·毒龙 01」「姬子 压墙式」「朽叶×姬子 双重骑乘」
 * 这类标题 —— 用户口径：**规则34 不许出现人物/角色的名字**。
 *
 * 修法有两道：
 *   ① 提示词层：不再把角色名告诉模型（治本，`buildGalleryFormatPrompt`）。
 *   ② 出口层：任何进标题/正文/署名的文本再过一遍本函数（兜底 —— 模型仍可能自行编出名字）。
 *
 * 本文件只做 ②，是**纯函数、零依赖**，供 `mediaService`（生成时）与 `db/index.js`
 * （一次性迁移，清洗历史数据）共用，避免两处各写一份正则（改一处漏一处）。
 *
 * ── 为什么"名字要连分隔符一起吃掉" ──
 *
 * 模型给的标题几乎都是「名字 + 分隔符 + 内容」：`爻光·毒龙 01`、`姬子 压墙式`、
 * `姬子×朽叶 双重骑乘`。只把名字删掉会留下 `·毒龙 01` 这种以标点开头的残句，
 * 所以匹配时把名字**连同紧随其后的 `·•×、,，|-—/` 一起**吃掉，最后再清一次首尾标点。
 */

/*
 * ⚠ 分隔符字符集**只能有一份定义**，且必须是"字符串"而不是正则字面量。
 *
 * 踩过的坑：写成正则字面量 `/[\s·•×、，,|\\-—/]/` 时，`\\` 是"转义反斜杠"，
 * 紧随其后的 `-` 就成了**范围运算符** → 实际构造出 `\`(U+005C) 到 `—`(U+2014)
 * 这个巨大的区间，把 a-z / A-Z 全部吃进去 —— 表现为 `doggystyle` 这种纯英文标签
 * 被整条清空（测试里 `tags.includes('doggystyle')` 变假）。
 * 用字符串构建（`'\\-'` → 正则源里的 `\-` = 转义连字符）才安全。
 *
 * 另：
 *   - **不含**拉丁字母 x / X —— 免得把正常英文词（如 `x-ray`）切坏。
 *   - **不含** `,` `，` —— 它们是**正文标点**，不是"名字与内容之间的连接符"。
 *     实测：备注「本来只想画姬子，结果下面那位太抢戏」若把 `，` 一并吃掉，
 *     会变成「本来只想画结果下面…」（少了逗号，句子黏成一团）。
 */
const SEPARATOR_CHARS = '·•×、|\\-—/';                    // 注意 `\\-` = 转义连字符
const SEPARATOR_CLASS = `[${SEPARATOR_CHARS}]`;           // 单字符的"分隔符类"
const EDGE_TRIM_RE = new RegExp(`^[\\s${SEPARATOR_CHARS}]+|[\\s${SEPARATOR_CHARS}]+$`, 'g');

function escapeRe(s) {
  return String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * 洗掉文本里出现的角色名（连名字后的分隔符一起）。
 *
 * @param {string} text 待清洗文本（title / content / author_name …）
 * @param {Iterable<string>} [names] 角色名清单（建议传**全库** `characters.display_name`）
 * @returns {string} 清洗后的文本；入参非法时原样返回，绝不抛错（迁移里在循环内调用）
 */
export function stripCharacterNames(text, names = []) {
  let s = String(text ?? '');
  if (!s) return s;

  const list = [...new Set(
    (names || [])
      .map(n => String(n ?? '').trim())
      .filter(n => n.length >= 2),          // 单字名噪声太大（「花」「云」会误伤），不处理
  )].sort((a, b) => b.length - a.length);   // ★ 长名优先：否则「朽叶」会先把「朽叶XX」切走一半

  for (const n of list) {
    // ★ 替换成**空串**而不是空格：中文不用空格分词，插空格会在句中留下
    //   「本来只想画 结果…」这类断口（替换时 `\s*` 已把两侧空白一并吃掉，
    //   所以「姬子 压墙式」→「压墙式」不会粘连）。
    s = s.replace(
      new RegExp(`\\s*${escapeRe(n)}\\s*${SEPARATOR_CLASS}*\\s*`, 'g'),
      '',
    );
  }

  return s.replace(/[ \t]{2,}/g, ' ').replace(EDGE_TRIM_RE, '').trim();
}
