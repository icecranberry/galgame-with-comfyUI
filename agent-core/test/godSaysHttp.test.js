import { godCommitGuard } from '../src/services/godSays/commitGuard.js';
import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import { once } from 'node:events';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import sharp from 'sharp';
import { GOD_TOOLS } from '../src/services/godSays/tools.js';
import { createGodRepository } from '../src/services/godSays/repository.js';
import { TIME_RULE } from '../src/services/godSays/promptBuilder.js';

test('HTTP native-tool loop streams, reconnects, and deduplicates without contacting external services', async t => {
  const logs = [];
  t.mock.method(console, 'log', (...parts) => logs.push(parts.join(' ')));
  process.env.DB_PATH = ':memory:';
  const imageDir = fs.mkdtempSync(path.join(os.tmpdir(), 'linshe-angel-http-'));
  process.env.IMAGES_DIR = imageDir;
  t.after(() => { assert.equal(path.dirname(imageDir), fs.realpathSync(os.tmpdir())); fs.rmSync(imageDir, { recursive: true }); });
  const { config } = await import('../src/config.js');
  config.dbPath = ':memory:';
  config.features.schedule = false;
  const nativeFetch = globalThis.fetch;
  t.mock.method(globalThis, 'fetch', (url, options) => {
    if (String(url).endsWith('/object_info')) return Promise.resolve(new Response('{}', { headers: { 'Content-Type': 'application/json' } }));
    if (!String(url).startsWith('http://127.0.0.1:')) throw new Error('External network forbidden in this test');
    return nativeFetch(url, options);
  });
  const requests = [];
  const personaRequests = [];
  const persona = '你是天使。\n## 你的身份\n你守着云庭的晨钟，负责接住神的低语，再把能做到的事情一件件做好。\n## 你的性格\n你认真而好奇，喜欢用轻快的短句说话。整理星图时常嫌麻烦，却总会多核对一次；遇到无法确认的事，会先停下来弄清楚。\n## 你的好恶\n你喜欢热茶和羽毛书签，讨厌空口承诺。\n## 你的外观\n你留浅金短发，有白羽和光环，穿着袖口绣星星的长袍。';
  const provider = express();
  provider.use(express.json({ limit: '2mb' }));
  provider.post('/chat/completions', (req, res) => {
    if (!req.body.stream) {
      personaRequests.push(req.body);
      return res.json({ choices: [{ message: { content: persona }, finish_reason: 'stop' }] });
    }
    requests.push(req.body);
    res.setHeader('Content-Type', 'text/event-stream');
    const emit = (delta, finish_reason = null) => res.write(`data: ${JSON.stringify({ choices: [{ index: 0, delta, finish_reason }] })}\n\n`);
    emit({ reasoning_content: '先确认工具的实际返回，再说明执行状态。' });
    if (requests.length === 1) {
      emit({ tool_calls: [{ index: 0, id: 'inspect-1', type: 'function', function: { name: 'inspect_neighbors', arguments: '{}' } }] }, 'tool_calls');
    } else if (requests.length === 2) {
      emit({ tool_calls: [{ index: 0, id: 'group-1', type: 'function', function: { name: 'create_group', arguments: JSON.stringify({ name: '彩虹茶话会', member_ids: [2, 3] }) } }] }, 'tool_calls');
    } else if (requests.length === 3) {
      emit({ tool_calls: [{ index: 0, id: 'world-1', type: 'function', function: { name: 'create_world_event', arguments: JSON.stringify({ title: '天空的彩虹', fact: '所有人看到天空出现一道巨大的彩虹', moment_count: 0, group_count: 0 }) } }] }, 'tool_calls');
    } else emit({ content: '吾神，彩虹已经落在天幕上。这次没有安排主动回应。' }, 'stop');
    res.end('data: [DONE]\n\n');
  });
  const modelServer = provider.listen(0, '127.0.0.1');
  await once(modelServer, 'listening');
  t.after(() => modelServer.close());
  Object.assign(config.llm, { freeEgg: false, connectionType: 'openai', baseURL: `http://127.0.0.1:${modelServer.address().port}`, apiKey: 'local-test', model: 'deepseek-test', thinkingMode: 'disabled', extraBody: { thinking: { type: 'disabled' } } });
  const { getDb, getSystemRules, getWorldSetting } = await import('../src/db/index.js');
  const db = getDb();
  db.prepare('UPDATE world_settings SET is_active=0').run();
  db.prepare("INSERT INTO world_settings(name,content,is_active,sort_order) VALUES ('天使创作测试','世界由浮岛组成，居民以星砂记录往事。',1,0)").run();
  db.prepare("INSERT INTO characters(id,name,display_name,base_prompt) VALUES (2,'a','阿晴','温柔'),(3,'b','小雨','好奇')").run();
  const repo = createGodRepository(db);
  repo.ensureAngel();
  config.features.schedule = true;
  db.prepare('UPDATE god_angel SET schedule_json=?,schedule_generated_at=? WHERE id=1').run(JSON.stringify([{ startTime: '00:00', endTime: '23:59', activity: '整理星图' }]), `${repo.day()}T00:00:00`);
  db.prepare("UPDATE god_angel SET summoned_at='2026-01-01T00:00:00.000Z' WHERE id=1").run();
  const { resetClient } = await import('../src/llm/llm-client.js');
  resetClient();
  const { default: router } = await import('../src/routes/godSays.js');
  // 即使关闭日程，也必须经天使专用生成器创建持久人格。
  config.features.schedule = false;
  const { getGodRuntime } = await import('../src/services/godSays/runtime.js');
  await getGodRuntime().ensureSchedule(repo.today());
  assert.equal(personaRequests.length, 1);
  assert.ok(personaRequests[0].messages.some(m => m.content.includes('角色人格设计师')));
  assert.match(personaRequests[0].messages[0].content, /<world_setting>[\s\S]*世界由浮岛组成/);
  assert.match(personaRequests[0].messages[1].content, /<world_integration[\s\S]*人格卡的身份经历/);
  assert.match(personaRequests[0].messages.at(-1).content, /严格遵循 <world_setting> 的设定/);
  assert.doesNotMatch(JSON.stringify(personaRequests[0].messages), /VAD|valence|arousal|dominance|第一手素材/);
  assert.equal(personaRequests[0].messages.filter(m => m.role === 'user').length, 1);
  assert.equal(repo.ensureAngel().persona, persona);
  assert.equal(repo.ensureAngel().emotion_baseline, null);
  assert.ok(repo.ensureAngel().persona_generated_at);
  config.features.schedule = true;
  db.prepare('UPDATE god_angel SET schedule_json=?,schedule_generated_at=? WHERE id=1').run(JSON.stringify([{ startTime: '00:00', endTime: '23:59', activity: '整理星图' }]), `${repo.day()}T00:00:00`);
  const app = express();
  app.use(express.json());
  app.use(godCommitGuard);
  app.use('/api/god-says', router);
  app.use('/api/groups', (await import('../src/routes/groups.js')).default);
  app.use((err, req, res, next) => res.status(err.status || 500).json({ error: err.message }));
  const server = app.listen(0, '127.0.0.1');
  await once(server, 'listening');
  config.port = server.address().port;
  t.after(() => server.close());
  const base = `http://127.0.0.1:${server.address().port}/api/god-says`;
  const draftState = await fetch(`${base}/state`).then(r => r.json());
  assert.equal(draftState.session.id, null);
  assert.equal(draftState.current, true);
  assert.deepEqual(draftState.worldEvents, []);
  assert.deepEqual(await fetch(`${base}/sessions`).then(r => r.json()), []);
  assert.equal(db.prepare('SELECT COUNT(*) n FROM god_sessions').get().n, 0);
  const send = () => fetch(`${base}/runs`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ client_id: 'http-run-001', text: '建立彩虹茶话会，让天空出现巨大的彩虹' }) }).then(r => r.json());
  const first = await send();
  assert.equal(first.duplicate, false);
  const eventsText = await fetch(`${base}/runs/${first.run.id}/stream`).then(r => r.text());
  assert.match(eventsText, /reasoning/);
  assert.match(eventsText, /天空的彩虹/);
  assert.match(eventsText, /completed/);
  assert.equal(requests.length, 4);
  assert.ok(requests.every(r => r.thinking.type === 'enabled' && r.stream && r.tools.length === GOD_TOOLS.length));
  const prefix = `${getSystemRules({ roleplay: false })}\n\n【语言要求】思考过程和最终回复都必须使用简体中文。`;
  assert.ok(requests.every(r => r.messages[0].role === 'system' && r.messages[0].content.startsWith(prefix)));
  const worldSetting = getWorldSetting();
  if (worldSetting) assert.ok(requests.every(r => r.messages[0].content.indexOf('【语言要求】') < r.messages[0].content.indexOf(worldSetting)));
  assert.ok(requests.every(r => r.messages.some(m => m.role === 'system' && m.content === persona)));
  const currentInput = requests[0].messages.at(-1);
  assert.equal(currentInput.role, 'user');
  assert.match(currentInput.content, /^<dynamic_context>[\s\S]*<schedule_context>[\s\S]*整理星图/);
  assert.ok(currentInput.content.endsWith('</dynamic_context>\n\n建立彩虹茶话会，让天空出现巨大的彩虹'));
  assert.ok(requests[0].messages.some(m => m.role === 'system' && m.content.includes('<dialogue_rules>')));
  // 静态时间规则会引用“当前日期时间”这个词，不能把规则本身误判为当次时间数据。
  assert.ok(requests[0].messages.filter(m => m.role === 'system').every(m => !m.content.replace(TIME_RULE, '').includes('当前日期时间') && !m.content.includes('"startTime"')));
  assert.equal(personaRequests.length, 1, 'tool rounds reuse the saved angel persona');
  assert.match(logs.join('\n'), new RegExp(`${first.run.id}/round-1`));
  assert.match(logs.join('\n'), /思考链/);
  assert.match(logs.join('\n'), /工具调用/);
  assert.match(logs.join('\n'), /先确认工具的实际返回/);
  assert.equal(requests[1].messages.at(-1).role, 'tool');
  assert.equal(requests[1].messages.at(-1).tool_call_id, 'inspect-1');
  assert.equal(requests[2].messages.at(-1).tool_call_id, 'group-1');
  assert.equal(requests[3].messages.at(-1).tool_call_id, 'world-1');
  assert.equal((await send()).duplicate, true);
  assert.equal(db.prepare('SELECT COUNT(*) n FROM god_world_events').get().n, 1);
  assert.equal(db.prepare('SELECT COUNT(*) n FROM group_chats').get().n, 1, '新增群聊直接创建');
  const state = await fetch(`${base}/state`).then(r => r.json());
  assert.equal(state.runs[0].status, 'completed');
  assert.equal(state.changes.length, 0);
  assert.equal(db.prepare('SELECT COUNT(*) n FROM group_chats').get().n, 1);

  assert.equal(state.worldEvents.length, 1);
  assert.match(state.session.schedule_json, /整理星图/);
  assert.equal(state.toolCatalog.length, GOD_TOOLS.length);
  const resumed = await fetch(`${base}/runs/${first.run.id}/stream`, { headers: { 'Last-Event-ID': String(state.cursor) } }).then(r => r.text());
  assert.doesNotMatch(resumed, /"type":"delta"/);
  assert.match(resumed, /run_end/);
  assert.equal(requests.length, 4, 'reconnect and duplicate POST do not repeat generation');
  assert.equal((await fetch(`${base}/runs`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' })).status, 400);
  await fetch(`${base}/sessions`, { method: 'POST' });
  const other = repo.start('http-other-session', '另一段对话的独立内容').run;
  repo.finish(other.id, 'completed');
  const selectedState = await fetch(`${base}/state?session=${first.run.session_id}`).then(r => r.json());
  assert.equal(selectedState.current, false);
  assert.equal(selectedState.writable, true);
  const continuationBody = { client_id: 'http-resume-previous', text: '继续第一段', session_id: first.run.session_id };
  const continuationResponse = await fetch(`${base}/runs`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(continuationBody) });
  assert.equal(continuationResponse.status, 200);
  const continuation = await continuationResponse.json();
  assert.equal(continuation.run.session_id, first.run.session_id);
  await fetch(`${base}/runs/${continuation.run.id}/stream`).then(r => r.text());
  assert.match(JSON.stringify(requests.at(-1).messages), /建立彩虹茶话会，让天空出现巨大的彩虹/);
  assert.doesNotMatch(JSON.stringify(requests.at(-1).messages), /另一段对话的独立内容/);
  assert.ok(requests.at(-1).messages.at(-1).content.endsWith('继续第一段'));
  for (const invalid of [0, -1, '1']) {
    assert.equal((await fetch(`${base}/runs`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ ...continuationBody, session_id: invalid }) })).status, 400);
  }
  const profile = { display_name: '星羽', persona: `${persona}\n你喜欢晨间的风。`, emotion_baseline: { valence: 0.6, arousal: 0.5, dominance: 0.4 } };
  assert.equal((await fetch(`${base}/angel`, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(profile) })).status, 200);
  assert.equal((await fetch(`${base}/angel`).then(r => r.json())).persona, profile.persona);
  assert.equal((await fetch(`${base}/angel`, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: '{}' })).status, 400);
  const { getImageDir } = await import('../src/services/imagePaths.js');
  assert.ok(getImageDir('avatargen').startsWith(imageDir + path.sep), 'media HTTP tests must never write real image directories');
  const png = `data:image/png;base64,${(await sharp({ create: { width: 4, height: 4, channels: 4, background: '#ddddff' } }).png().toBuffer()).toString('base64')}`;
  const upload = async kind => fetch(`${base}/angel/${kind}`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ base64: png }) }).then(r => r.json());
  const avatar = await upload('avatar'); assert.match(avatar.avatar_path, /\/images\/avatargen\/god_avatar_/);
  assert.equal((await fetch(`${base}/angel`).then(r => r.json())).avatar_path, avatar.avatar_path);
  const standing = await upload('standing'); assert.match(standing.standing_url, /\/images\/standing\/god_standing_/);
  assert.equal((await fetch(`${base}/angel`).then(r => r.json())).standing_url, standing.standing_url);
  assert.equal((await fetch(`${base}/angel/standing`, { method: 'DELETE' })).status, 200);
  assert.equal((await fetch(`${base}/angel`).then(r => r.json())).standing_url, null);
  const angelBeforeWardrobe = await fetch(`${base}/angel`).then(r => r.json());
  const outfitBody = { display_name: angelBeforeWardrobe.display_name, persona: angelBeforeWardrobe.persona,
    outfits: [{ scene: 'sleep', name: '云朵睡衣', description: 'white wings, a blue nightdress, barefoot' }] };
  assert.equal((await fetch(`${base}/angel`, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(outfitBody) })).status, 200);
  const sleepStanding = await fetch(`${base}/angel/standing`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ base64: png, scene: 'sleep' }) }).then(r => r.json());
  const sleepUrl = sleepStanding.standings.find(row => row.scene === 'sleep').image_url;
  assert.match(sleepUrl, /\/images\/standing\/god_standing_/);
  assert.equal(sleepStanding.standing_url, null);
  assert.equal((await fetch(`${base}/angel/standing?scene=sleep`, { method: 'DELETE' })).status, 200);
  const reopenedWardrobe = await fetch(`${base}/angel`).then(r => r.json());
  assert.equal(reopenedWardrobe.outfits.find(row => row.scene === 'sleep').name, '云朵睡衣');
  assert.equal(reopenedWardrobe.standings.find(row => row.scene === 'sleep').image_url, null);
  assert.equal((await fetch(`${base}/angel/clothing-draft`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' })).status, 400);
  assert.equal((await fetch(`${base}/angel/image-jobs`).then(r => r.json())).jobs.length, 0);
  assert.equal((await fetch(`${base}/angel/image-jobs/not-a-job`)).status, 404);
  assert.equal((await fetch(`${base}/angel/image-jobs`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{"kind":"bad"}' })).status, 400);
  assert.equal((await fetch(`${base}/runs/${continuation.run.id}`, { method: 'DELETE' })).status, 200);
  assert.equal((await fetch(`${base}/runs/${other.id}`, { method: 'DELETE' })).status, 200);
  assert.equal((await fetch(`${base}/runs/${first.run.id}`, { method: 'DELETE' })).status, 200);
  assert.equal((await fetch(`${base}/runs/${first.run.id}/stream`)).status, 404);
  assert.deepEqual(await fetch(`${base}/sessions`).then(r => r.json()), []);
  assert.deepEqual(await fetch(`${base}/memories`).then(r => r.json()), []);
  assert.equal(repo.snapshot().runs.length, 0);
  assert.equal(repo.snapshot().messages.length, 0);
  assert.equal(db.prepare('SELECT COUNT(*) n FROM god_world_events').get().n, 1);
});
