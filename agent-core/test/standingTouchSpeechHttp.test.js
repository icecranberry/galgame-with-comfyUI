import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

test('portrait speech HTTP flow reuses configured API voices, persists audio and truly regenerates without changing chat', async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'standing-speech-'));
  process.env.DB_PATH = path.join(dir, 'test.db');
  process.env.TTS_AUDIO_DIR = path.join(dir, 'audio');
  const originalFetch = globalThis.fetch;
  globalThis.fetch = (url, options) => String(url).endsWith('/object_info') ? Promise.resolve(Response.json({})) : originalFetch(url, options);
  t.after(() => { globalThis.fetch = originalFetch; });
  const { getDb, closeDb } = await import('../src/db/index.js');
  const { default: express } = await import('express');
  const { default: standingRoutes } = await import('../src/routes/expressionStandings.js');
  const { default: speechRoutes } = await import('../src/routes/tts.js');
  const { setSpeechSettings, speakMessage } = await import('../src/services/speechService.js');
  const { saveApiVoice } = await import('../src/services/speechConfig.js');
  const { standingSpeechProfile } = await import('../src/services/standingTouchSpeechRuntime.js');
  const { addClient, removeClient } = await import('../src/services/unifiedStreamBus.js');
  const events = [], client = { write: data => events.push(data) }; addClient(client);
  const app = express(); app.use(express.json());
  let calls = 0, upstreamFailure = false, concurrent = 0, maximum = 0;
  app.post('/synthesize', async (_req, res) => {
    calls++; concurrent++; maximum = Math.max(maximum, concurrent);
    await new Promise(resolve => setTimeout(resolve, 30)); concurrent--;
    if (upstreamFailure) return res.status(500).json({ error: 'mock upstream failure' });
    res.type('audio/mpeg').send(Buffer.from(`ID3fixture-${calls}`));
  });
  app.use('/api/tts', speechRoutes); app.use('/api', standingRoutes);
  app.use((error, _req, res, _next) => res.status(error.status || 500).json({ error: error.message }));
  const server = await new Promise(resolve => { const value = app.listen(0, '127.0.0.1', () => resolve(value)); });
  const base = `http://127.0.0.1:${server.address().port}`;
  t.after(async () => { removeClient(client); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); closeDb(); await fs.rm(dir, { recursive: true, force: true }); });
  const request = async (route, body, method = body === undefined ? 'GET' : 'POST', status = 200) => {
    const response = await fetch(base + '/api' + route, { method, headers: { 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
    const data = await response.json(); assert.equal(response.status, status, JSON.stringify(data)); return data;
  };
  const db = getDb();
  const id = Number(db.prepare('INSERT INTO characters(name,display_name,base_prompt) VALUES(?,?,?)').run('voice-test', '语音角色', 'test').lastInsertRowid);
  const unconfigured = Number(db.prepare('INSERT INTO characters(name,display_name,base_prompt) VALUES(?,?,?)').run('silent-test', '静默角色', 'test').lastInsertRowid);
  const route = `/characters/${id}/expression-standings/touch-lines`;
  const original = await request(route, { expectedVersion: null, lines: { head: ['摸摸头真舒服', '轻一点就好啦'], face: ['脸有些热呢'] } }, 'PUT');
  await request(`/characters/${unconfigured}/expression-standings/touch-lines`, { expectedVersion: null, lines: { head: ['我还没有声音'] } }, 'PUT');
  setSpeechSettings({ enabled: true, mode: 'api', api: { endpoint: base + '/synthesize', model: 'test-model' } });
  saveApiVoice(id, { voice: 'nova' });
  assert.ok(events.some(event => event.includes('"voiceChanged":true') && event.includes(`"characterId":${id}`)));
  assert.equal((await request(route)).speech.configured, true);
  assert.equal(standingSpeechProfile(db, id, { enabled: true, mode: 'local', local_model: 'index-tts' }).configured, false);
  const filled = await request('/expression-standings/touch-lines/speech/fill', {}, 'POST', 202);
  assert.equal(filled.started, 3); assert.ok(filled.skipped >= 1);
  assert.equal((await request('/expression-standings/touch-lines/speech/fill', {}, 'POST', 202)).started, 0);
  const terminal = async () => {
    for (let i = 0; i < 200; i++) {
      const state = await request(route);
      if (!Object.values(state.speech.lines).flat().some(line => ['queued', 'generating'].includes(line.status))) return state;
      await new Promise(resolve => setTimeout(resolve, 10));
    }
    assert.fail('speech did not finish');
  };
  let state = await terminal();
  assert.equal(calls, 3); assert.ok(maximum <= 2);
  const first = state.speech.lines.head[0]; assert.equal(first.status, 'completed');
  assert.equal((await fetch(base + first.audio_url)).status, 200);
  assert.ok(events.some(event => event.includes('touch-lines-speech')));
  const interaction = await request(`/characters/${id}/standing-interaction`);
  assert.equal(interaction.touchLines.speech.lines.head[0].audio_url, first.audio_url);
  const overview = await request('/expression-standings/overview');
  assert.equal(overview.characters.find(char => char.id === id).touchSpeech.ready, 3);
  const messageId = Number(db.prepare("INSERT INTO messages(conversation_id,role,content) VALUES(?,'assistant',?)").run(`char_${id}`, first.text).lastInsertRowid);
  assert.equal(speakMessage(id, messageId).id, first.job_id);
  const regenerate = () => request(route + '/speech', { expectedVersion: state.version, part: 'head', index: 0, force: true }, 'POST', 202);
  let pending = await regenerate();
  assert.notEqual(pending.speech.lines.head[0].job_id, first.job_id);
  assert.equal(pending.speech.lines.head[0].audio_url, first.audio_url);
  assert.equal((await regenerate()).summary.started, 0);
  state = await terminal();
  assert.equal(calls, 4); assert.notEqual(state.speech.lines.head[0].audio_url, first.audio_url);
  assert.equal(speakMessage(id, messageId).id, first.job_id);
  const newest = state.speech.lines.head[0];
  upstreamFailure = true; await regenerate(); state = await terminal();
  assert.equal(state.speech.lines.head[0].status, 'failed');
  assert.equal(state.speech.lines.head[0].audio_url, newest.audio_url);
  assert.equal((await fetch(base + first.audio_url)).status, 200);
  upstreamFailure = false;
  state = await request(route, { expectedVersion: state.version, lines: { ...state.lines, head: ['新台词不能误播旧音频', state.lines.head[1]] } }, 'PUT');
  assert.equal(state.speech.lines.head[0].audio_url, null);
  await request(route + '/speech', { expectedVersion: original.version }, 'POST', 409);
  assert.equal((await request(route + '/speech', { expectedVersion: state.version }, 'POST', 202)).summary.started, 1);
  state = await terminal();
  await fs.rm(path.join(dir, 'audio', 'generated', path.basename(state.speech.lines.head[0].audio_url)));
  assert.equal((await request(route)).speech.lines.head[0].status, 'failed');
  assert.equal((await request(route + '/speech', { expectedVersion: state.version }, 'POST', 202)).summary.started, 1);
  state = await terminal();
  closeDb();
  assert.equal((await request(route)).speech.lines.head[0].audio_url, state.speech.lines.head[0].audio_url);
  events.length = 0;
  const cleared = await request('/tts/cache', undefined, 'DELETE');
  assert.ok(cleared.ids.includes(state.speech.lines.head[0].job_id));
  assert.ok(events.some(event => event.includes('"voiceChanged":true') && event.includes(`"characterId":${id}`)));
  state = await request(route);
  assert.ok(Object.values(state.speech.lines).flat().every(line => !line.audio_url));
  assert.equal((await request(route + '/speech', { expectedVersion: state.version }, 'POST', 202)).summary.started, 3);
  state = await terminal();
  assert.ok(Object.values(state.speech.lines).flat().every(line => line.audio_url));
  events.length = 0;
  setSpeechSettings({ enabled: false });
  assert.ok(events.some(event => event.includes('"voiceChanged":true') && event.includes(`"characterId":${id}`)));
  assert.equal((await request(route + '/speech', { expectedVersion: state.version }, 'POST', 202)).summary.started, 0);
});
