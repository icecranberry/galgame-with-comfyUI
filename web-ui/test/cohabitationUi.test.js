import test from 'node:test'
import process from 'node:process'
import assert from 'node:assert/strict'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { mkdir } from 'node:fs/promises'
import { createCohabitationUiFixture } from './helpers/cohabitationUiFixture.js'

// Explicit opt-in: an installed Playwright package/browser is sufficient; no production server or DB is used.
test('宿舍真实界面：新建、拖放、搬迁、失败保留、键盘操作及四种视口主题', { skip: process.env.LINSHE_BROWSER_TEST !== '1', timeout: 120_000 }, async t => {
  const pw = await import(process.env.PLAYWRIGHT_MODULE_PATH ? pathToFileURL(process.env.PLAYWRIGHT_MODULE_PATH).href : 'playwright-core')
  const fixture = await createCohabitationUiFixture()
  const { db, characters } = fixture
  t.after(() => fixture.close())
  const browser = await pw.chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge', headless: true })
  t.after(() => browser.close())
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto(fixture.url)
  const output = fileURLToPath(new URL('../../output/cohabitation-ui/interaction/', import.meta.url)); await mkdir(output, { recursive: true })
  const entry = page.getByRole('button', { name: /^宿舍安排/ })
  await entry.waitFor()
  const relation = await page.getByRole('button', { name: /^我的关系图/ }).boundingBox()
  const residence = await entry.boundingBox()
  assert.ok(Math.abs(relation.width - residence.width) < 2)
  await page.screenshot({ path: output + 'tavern.png' })
  await entry.click()
  const notice = page.getByText('变更将在下一次自动/手动全体日程变更时生效', { exact: true })
  assert.equal(await notice.count(), 0, '未修改时不显示提示')
  const fresh = page.getByRole('button', { name: '新建房间，拖入头像可同时入住' })
  await page.route('**/api/cohabitation/rooms', route => route.fulfill({ status: 500, contentType: 'application/json', body: '{"error":"新建失败"}' }), { times: 1 })
  await fresh.click()
  await page.waitForFunction(() => window.notices.some(n => n[0] === '新建失败'))
  assert.equal(await notice.count(), 0, '保存失败不显示待生效提示')
  await fresh.click()
  const rooms = page.locator('.residence-room'), pool = page.locator('.residence-pool-avatars')
  await rooms.first().waitFor()
  await notice.waitFor()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.locator('.cohabitation-body').waitFor({ state: 'detached' })
  await entry.click()
  await rooms.first().waitFor()
  await notice.waitFor()
  assert.equal(await rooms.getByRole('textbox').count(), 0, '房名默认是标题，不常驻输入框')
  const beginEdit = async room => {
    await room.getByRole('button', { name: /^修改.*的名称$/ }).click()
    const input = room.getByRole('textbox')
    await page.waitForFunction(() => document.activeElement?.closest('.residence-name-editor'))
    return input
  }
  const firstName = await beginEdit(rooms.first()); await firstName.fill('晨光居室'); await firstName.press('Enter')
  await page.getByRole('button', { name: '将选中的角色移入晨光居室' }).waitFor()
  await page.getByRole('button', { name: '修改晨光居室的名称' }).waitFor()
  const unsaved = await beginEdit(rooms.first())
  await unsaved.fill('尚未保存')
  await unsaved.dispatchEvent('keydown', { key: 'Enter', isComposing: true, bubbles: true })
  assert.equal(db.prepare('SELECT name FROM cohabitation_rooms ORDER BY id').get().name, '晨光居室')
  await unsaved.press('Escape')
  await page.getByRole('button', { name: '修改晨光居室的名称' }).waitFor()
  assert.equal(await fresh.isVisible(), true, 'Esc只取消改名，不关闭弹窗')
  await page.getByRole('button', { name: '选择林舟', exact: true }).dragTo(page.getByRole('button', { name: '将选中的角色移入晨光居室' }))
  await rooms.first().getByRole('button', { name: '选择林舟', exact: true }).waitFor()
  assert.equal(await pool.getByRole('button').count(), 3)
  await page.getByRole('button', { name: '选择苏晴', exact: true }).dragTo(fresh)
  await rooms.nth(1).getByRole('button', { name: '选择苏晴', exact: true }).waitFor()
  const secondName = await beginEdit(rooms.nth(1)); await secondName.fill('晚风居室'); await secondName.press('Enter')
  await page.getByRole('button', { name: '将选中的角色移入晚风居室' }).waitFor()
  await page.getByRole('button', { name: '修改晚风居室的名称' }).waitFor()
  const secondId = db.prepare("SELECT id FROM cohabitation_rooms WHERE name='晚风居室'").get().id
  await page.route('**/api/cohabitation/rooms/' + secondId, route => route.fulfill({ status: 500, contentType: 'application/json', body: '{"error":"改名失败"}' }), { times: 1 })
  const failedName = await beginEdit(rooms.nth(1)); await failedName.fill('晚风小屋'); await failedName.press('Enter')
  await rooms.nth(1).getByRole('alert').waitFor()
  assert.equal(await failedName.inputValue(), '晚风小屋', '保存失败保留输入')
  assert.equal(db.prepare('SELECT name FROM cohabitation_rooms WHERE id=?').get(secondId).name, '晚风居室')
  await failedName.press('Enter')
  await page.getByRole('button', { name: '修改晚风小屋的名称' }).waitFor()
  const restoreName = await beginEdit(rooms.nth(1)); await restoreName.fill('晚风居室'); await restoreName.press('Tab')
  await page.getByRole('button', { name: '修改晚风居室的名称' }).waitFor()
  await page.getByRole('button', { name: '选择林舟', exact: true }).dragTo(page.getByRole('button', { name: '将选中的角色移入晚风居室' }))
  await rooms.nth(1).getByRole('button', { name: '选择林舟', exact: true }).waitFor()
  assert.equal(db.prepare('SELECT COUNT(*) n FROM cohabitation_members WHERE character_id=?').get(characters[0].id).n, 1)
  // A failed move must leave the original room and the selected avatar intact.
  await page.route('**/api/cohabitation/members/' + characters[0].id, route => route.fulfill({ status: 500, contentType: 'application/json', body: '{"error":"验收用保存失败"}' }), { times: 1 })
  await page.getByRole('button', { name: '选择林舟', exact: true }).click()
  await page.getByRole('button', { name: '将选中的角色移入晨光居室' }).click()
  await page.waitForFunction(() => window.notices.some(n => n[0] === '验收用保存失败'))
  assert.equal(await rooms.nth(1).getByRole('button', { name: '选择林舟', exact: true }).getAttribute('aria-pressed'), 'true')
  await page.getByRole('button', { name: '将选中的角色移入晨光居室' }).press('Enter')
  await rooms.first().getByRole('button', { name: '选择林舟', exact: true }).waitFor()
  await page.getByRole('button', { name: '选择周宁', exact: true }).press('Enter')
  await page.getByRole('button', { name: '将选中的角色移入晨光居室' }).press('Enter')
  await rooms.first().getByRole('button', { name: '选择周宁', exact: true }).waitFor()
  await page.getByRole('button', { name: '选择许棠', exact: true }).click()
  await page.getByRole('button', { name: '将选中的角色移入晚风居室' }).click()
  await rooms.nth(1).getByRole('button', { name: '选择许棠', exact: true }).waitFor()
  for (const [label, width, height] of [['desktop', 1280, 900], ['mobile', 390, 844]]) {
    await page.setViewportSize({ width, height })
    for (const theme of ['warm', 'dark']) {
      await page.evaluate(value => document.documentElement.dataset.theme = value, theme)
      await page.waitForFunction(() => document.getAnimations().every(a => a.playState === 'finished'))
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), label + ' no horizontal overflow')
      await page.screenshot({ path: output + label + '-' + theme + '.png' })
      // 拖入轮廓向外延伸 4px；滚动容器必须为首列、末列留出绘制空间。
      await page.locator('.residence-main').evaluate(el => { el.scrollTop = 0 })
      const transfer = await page.evaluateHandle(id => { const data = new DataTransfer(); data.setData('application/x-linshe-character', String(id)); return data }, characters[0].id)
      await rooms.first().dispatchEvent('dragover', { dataTransfer: transfer })
      const edge = await rooms.first().evaluate(el => {
        const box = el.getBoundingClientRect(), host = el.closest('.residence-main').getBoundingClientRect(), style = getComputedStyle(el)
        const extent = parseFloat(style.outlineWidth) + parseFloat(style.outlineOffset)
        return { left: box.left - extent >= host.left, right: box.right + extent <= host.right }
      })
      assert.ok(edge.left && edge.right, label + '拖入高亮两侧不被裁切')
      await page.screenshot({ path: output + label + '-' + theme + '-drag.png' })
      await rooms.first().dispatchEvent('dragleave')
      await transfer.dispose()
    }
  }
  await page.getByRole('button', { name: '选择许棠', exact: true }).click()
  await page.getByRole('button', { name: '移出房间', exact: true }).click()
  await pool.getByRole('button', { name: '选择许棠', exact: true }).waitFor()
  await page.getByRole('button', { name: '删除晚风居室，成员移回未安排' }).click()
  await pool.getByRole('button', { name: '选择苏晴', exact: true }).waitFor()
  assert.equal(db.prepare('SELECT COUNT(*) n FROM cohabitation_rooms').get().n, 1)
  await page.reload(); await entry.click()
  await page.getByRole('button', { name: '修改晨光居室的名称' }).waitFor()
  await rooms.first().getByRole('button', { name: '选择林舟', exact: true }).waitFor()
  assert.equal(await rooms.count(), 1, '刷新后从独立数据库读回已保存名称和成员')
  await notice.waitFor()
  await page.setViewportSize({ width: 1280, height: 900 })
  const layoutBox = await page.locator('.residence-layout').boundingBox(), poolBox = await page.locator('.residence-pool').boundingBox()
  assert.ok(poolBox.width >= 340 && poolBox.width / layoutBox.width >= .37, '右侧扩大至约四成')
  // Browser 200% zoom halves the CSS viewport and doubles its pixel density.
  const reading = await browser.newPage({ viewport: { width: 640, height: 450 }, deviceScaleFactor: 2 })
  await reading.goto(fixture.url)
  await reading.getByRole('button', { name: /^宿舍安排/ }).click()
  await reading.getByRole('button', { name: '修改晨光居室的名称' }).waitFor()
  await reading.waitForFunction(() => document.getAnimations().every(a => a.playState === 'finished'))
  assert.ok(await reading.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '200%等效阅读重排不横向溢出')
  await reading.screenshot({ path: output + 'reading-200.png' })
  await reading.close()
  const { saveAppliedResidences, listResidences } = await import('../../agent-core/src/db/cohabitationRepository.js')
  saveAppliedResidences(db, listResidences(db))
  await page.reload(); await entry.click()
  await rooms.first().waitFor()
  assert.equal(await notice.count(), 0, '成功生效后重新打开清除提示')
  const title = await beginEdit(rooms.first()); await title.fill('等待下轮'); await title.press('Enter')
  await page.getByRole('button', { name: '修改等待下轮的名称' }).waitFor()
  await notice.waitFor()
  const revert = await beginEdit(rooms.first()); await revert.fill('晨光居室'); await revert.press('Enter')
  await notice.waitFor({ state: 'detached' })
  assert.deepEqual(errors, [])
})
