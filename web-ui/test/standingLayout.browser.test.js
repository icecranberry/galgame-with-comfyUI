import test from 'node:test'
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

test('standing layout reserves two lines and keeps its size across updates', { skip: !process.env.PLAYWRIGHT_MODULE, timeout: 60000 }, async t => {
  const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE)
  const { createServer } = await import('vite')
  const { default: vue } = await import('@vitejs/plugin-vue')
  const server = await createServer({ configFile: false, root: fileURLToPath(new URL('../', import.meta.url)), plugins: [vue()], server: { host: '127.0.0.1', port: 0 } })
  await server.listen()
  const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || undefined })
  t.after(async () => { await browser.close(); await server.close() })
  for (const viewport of [{ width: 390, height: 844 }, { width: 844, height: 390 }, { width: 480, height: 800 }]) {
    const page = await browser.newPage({ viewport, reducedMotion: 'reduce' })
    await page.goto(`${server.resolvedUrls.local[0]}test/fixtures/standingInteraction.html`)
    await page.waitForSelector('.standing-image')
    await page.waitForFunction(() => document.querySelector('[data-standing-region="head"]')?.getAttribute('aria-disabled') === 'false')
    const image = page.locator('.standing-image')
    const initial = await image.boundingBox()
    assert.ok(Math.abs(initial.y + initial.height - viewport.height) < 1)
    const reserved = await page.locator('.standing-headroom').evaluate(el => el.getBoundingClientRect().height)
    assert.ok(Math.abs(initial.height - Math.min(viewport.height - reserved, viewport.width * 720 / 200)) < 1, 'portrait uses all available space while preserving its proportions')
    await page.getByText('聊天更新', { exact: true }).evaluate(el => el.click())
    const reason = page.locator('.standing-reason')
    await reason.waitFor()
    const thoughtText = page.locator('.thought-text')
    assert.ok(await thoughtText.evaluate(el => el.clientHeight < 1.5 * parseFloat(getComputedStyle(el).lineHeight)), 'short thoughts use one line')
    await thoughtText.evaluate(el => { el.textContent = '这是需要换行显示的内心活动。'.repeat(20) })
    const reasonBox = await reason.boundingBox()
    assert.ok(reasonBox.y >= 15, 'two-line thought bubble fits within the top safe margin')
    if (initial.width < viewport.width - 1) assert.ok(reasonBox.y < 18, 'two-line thought bubble uses the reserved space without excessive empty margin')
    assert.ok(await thoughtText.evaluate(el => el.clientHeight >= 2 * parseFloat(getComputedStyle(el).lineHeight) - 1))
    await page.locator('[data-standing-region="head"]').evaluate(el => el.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true })))
    const note = page.locator('.interaction-note')
    await note.waitFor()
    const noteText = page.locator('.interaction-text')
    assert.ok(await noteText.evaluate(el => el.clientHeight < 1.5 * parseFloat(getComputedStyle(el).lineHeight)), 'short replies use one line')
    await noteText.evaluate(el => { el.textContent = '这是需要换行显示的触摸反馈。'.repeat(20) })
    const noteBox = await note.boundingBox()
    assert.ok(noteBox.y >= 15, 'two-line touch bubble fits within the top safe margin')
    assert.ok(await noteText.evaluate(el => el.clientHeight >= 2 * parseFloat(getComputedStyle(el).lineHeight) - 1))
    await page.getByText('切换构图', { exact: true }).evaluate(el => el.click())
    await page.waitForTimeout(400)
    const after = await image.boundingBox()
    assert.ok(Math.abs(after.width - initial.width) < 1 && Math.abs(after.height - initial.height) < 1)
    await page.close()
  }
})
