import test from 'node:test'
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { mkdir } from 'node:fs/promises'
import path from 'node:path'

test('语言风格在双主题桌面/窄屏可润色、保存、清空，失败和过期响应保留正确草稿', { skip: !process.env.PLAYWRIGHT_MODULE, timeout: 60000 }, async t => {
  const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE)
  const { createServer } = await import('vite')
  const { default: vue } = await import('@vitejs/plugin-vue')
  const server = await createServer({ configFile: false, root: fileURLToPath(new URL('../', import.meta.url)), plugins: [vue()], server: { host: '127.0.0.1', port: 0 } })
  await server.listen()
  t.after(() => server.close())
  const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || undefined })
  t.after(() => browser.close())
  const page = await browser.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const base = `${server.resolvedUrls.local[0]}test/fixtures/worldLanguageStyle.html`
  const screenshots = process.env.LANGUAGE_STYLE_SCREENSHOTS
  if (screenshots) await mkdir(screenshots, { recursive: true })
  const input = page.getByRole('textbox', { name: '额外语言风格' })
  const save = page.getByRole('button', { name: '保存', exact: true })
  const polish = page.getByRole('button', { name: '一键润色', exact: true })
  for (const theme of ['warm', 'dark']) for (const width of [1280, 375, 320]) {
    await page.setViewportSize({ width, height: 850 })
    await page.goto(`${base}?theme=${theme}`)
    await input.waitFor()
    await input.fill('温柔一点，含蓄幽默')
    await polish.click()
    await page.waitForFunction(() => document.querySelector('textarea')?.value.startsWith('## 文风要求：'))
    assert.equal(await page.evaluate(() => languageStyleFixture.state.saved.length), 0, '润色不能自动保存')
    await page.waitForTimeout(350)
    const panel = page.locator('.modal-panel').last()
    const box = await panel.boundingBox()
    assert.ok(box.x >= 0 && box.x + box.width <= width + 1)
    assert.ok(await panel.evaluate(el => el.scrollWidth <= el.clientWidth + 1))
    const polishBox = await polish.boundingBox(), inputBox = await input.boundingBox()
    assert.ok(polishBox.y + polishBox.height <= inputBox.y && Math.abs(polishBox.x + polishBox.width - inputBox.x - inputBox.width) < 2, '润色位于 textarea 右上方并右对齐')
    const cancelBox = await page.getByRole('button', { name: '取消', exact: true }).boundingBox()
    assert.ok(Math.abs(polishBox.height - cancelBox.height) < 1, '润色使用与常规操作相同的按钮高度')
    assert.equal(await panel.evaluate(el => getComputedStyle(el.closest('.modal-overlay')).getPropertyValue('--linshe-modal-duration')), '300ms')
    if (screenshots) await page.screenshot({ path: path.join(screenshots, `${theme}-${width}.png`) })
    await save.click()
    await input.waitFor({ state: 'hidden' })
    const requests = await page.evaluate(() => languageStyleFixture.state.requests)
    assert.deepEqual(Object.keys(requests.at(-1).body), ['language_style'], '保存不能覆盖世界观草稿')
    await page.getByRole('button', { name: '语言风格', exact: true }).click()
    assert.match(await input.inputValue(), /### 禁止事项[\s\S]*### 例句/)
    await input.fill('')
    await save.click()
    await input.waitFor({ state: 'hidden' })
    assert.equal(await page.evaluate(() => languageStyleFixture.state.languageStyle), '')
  }
  await page.goto(base)
  await input.fill('失败后保留的需求')
  await page.evaluate(() => { languageStyleFixture.state.mode = 'error' })
  await polish.click()
  await page.getByRole('alert').waitFor()
  assert.equal(await input.inputValue(), '失败后保留的需求')
  await page.evaluate(() => { languageStyleFixture.state.mode = 'saveError' })
  await save.click()
  await page.getByText('测试保存失败', { exact: true }).waitFor()
  assert.equal(await input.inputValue(), '失败后保留的需求')
  await page.evaluate(() => { languageStyleFixture.state.mode = 'pending' })
  await polish.click()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await input.waitFor({ state: 'hidden' })
  await page.evaluate(() => { languageStyleFixture.state.worldId = 2; languageStyleFixture.state.languageStyle = '另一套世界的原文'; languageStyleFixture.state.open = true })
  await input.waitFor()
  await page.evaluate(() => languageStyleFixture.finishPolish())
  await page.waitForTimeout(350)
  assert.equal(await input.inputValue(), '另一套世界的原文', '已关闭窗口的请求不能覆盖新世界的草稿')
  assert.deepEqual(errors, [])
})
