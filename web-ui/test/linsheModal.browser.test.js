import test from 'node:test'
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import process from 'node:process'

test('统一弹窗：层级、关闭拦截、退出动画、焦点与触屏尺寸', { skip: !process.env.PLAYWRIGHT_MODULE, timeout: 60000 }, async t => {
  const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE)
  const { createServer } = await import('vite')
  const { default: vue } = await import('@vitejs/plugin-vue')
  const server = await createServer({ configFile: false, root: fileURLToPath(new URL('../', import.meta.url)), plugins: [vue()], server: { host: '127.0.0.1', port: 0 } })
  await server.listen()
  t.after(() => server.close())
  const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge', headless: true })
  t.after(() => browser.close())
  const page = await browser.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${server.resolvedUrls.local[0]}test/fixtures/linsheModal.html`)
  const outer = page.getByRole('dialog', { name: '主窗口', exact: true })
  const inner = page.getByRole('dialog', { name: '子窗口', exact: true })
  const openInner = async () => { await outer.getByRole('button', { name: '打开子窗口' }).click(); await inner.waitFor() }
  await page.getByRole('button', { name: '打开主窗口' }).click()
  await openInner()
  assert.ok(await inner.evaluate(el => Number(getComputedStyle(el.parentElement).zIndex)) > await outer.evaluate(el => Number(getComputedStyle(el.parentElement).zIndex)))
  await page.keyboard.press('Escape')
  await page.waitForFunction(() => !window.modalFixture.inner)
  assert.equal(await inner.count(), 1, '离场动画期间保留节点')
  await page.keyboard.press('Escape')
  await inner.waitFor({ state: 'detached' })
  assert.equal(await outer.count(), 1, '重复 Esc 不穿透正在退出的子窗口')
  assert.equal(await page.evaluate(() => document.activeElement.textContent), '打开子窗口')

  await openInner()
  await page.evaluate(() => { window.modalFixture.disabled = true })
  assert.equal(await inner.getByRole('button', { name: '关闭', exact: true }).isDisabled(), true)
  await page.keyboard.press('Escape')
  await page.mouse.click(2, 2)
  assert.equal(await page.evaluate(() => window.modalFixture.inner), true)
  await page.evaluate(() => { window.modalFixture.disabled = false; window.modalFixture.guard = true })
  await inner.getByRole('button', { name: '关闭', exact: true }).click()
  assert.equal(await inner.getByRole('button', { name: '关闭', exact: true }).isDisabled(), true)
  await page.evaluate(() => window.resolveModalGuard(false))
  await page.waitForFunction(() => !document.querySelectorAll('.linshe-modal')[1].querySelector('[aria-label="关闭"]').disabled)
  assert.equal(await page.evaluate(() => window.modalFixture.inner), true)
  await page.evaluate(() => { window.modalFixture.guard = false; window.modalFixture.error = true })
  await inner.getByRole('button', { name: '关闭', exact: true }).click()
  assert.equal(await page.evaluate(() => window.modalFixture.guarded && window.modalFixture.inner), true)
  await page.evaluate(() => { window.modalFixture.error = false; window.modalFixture.backdrop = false })
  await page.mouse.click(2, 2)
  assert.equal(await page.evaluate(() => window.modalFixture.inner), true)
  await page.evaluate(() => { window.modalFixture.backdrop = true })
  const rect = await inner.boundingBox()
  await page.mouse.move(rect.x + 10, rect.y + 10); await page.mouse.down(); await page.mouse.move(2, 2); await page.mouse.up()
  assert.equal(await page.evaluate(() => window.modalFixture.inner), true, '从面板拖到遮罩不关闭')
  await page.mouse.click(2, 2)
  await inner.waitFor({ state: 'detached' })

  await outer.getByRole('button', { name: '最后一个操作' }).focus()
  await page.keyboard.press('Tab')
  assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), '关闭')
  await page.keyboard.press('Shift+Tab')
  assert.equal(await page.evaluate(() => document.activeElement.textContent), '最后一个操作')
  for (const theme of ['warm', 'dark']) for (const width of [1280, 360]) {
    await page.setViewportSize({ width, height: 800 })
    await page.evaluate(value => { document.documentElement.dataset.theme = value }, theme)
    const close = outer.getByRole('button', { name: '关闭', exact: true })
    const box = await close.boundingBox()
    assert.ok(box.width >= 44 && box.height >= 44)
    const panel = await outer.boundingBox()
    assert.ok(panel.x >= 0 && panel.x + panel.width <= width)
  }
  await outer.getByRole('button', { name: '关闭', exact: true }).click()
  await outer.waitFor({ state: 'detached' })
  assert.equal(await page.evaluate(() => document.activeElement.textContent), '打开主窗口')
  assert.deepEqual(errors, [])
})
